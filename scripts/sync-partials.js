#!/usr/bin/env node
/* Sync shared partials (nav + footer) into every page.
 *
 * Single source of truth:
 *   - /partials/nav.html      + /assets/css/nav.css    + /assets/js/nav.js
 *   - /partials/footer.html   + /assets/css/footer.css
 *
 * Each partial is injected into every top-level *.html between its
 * START/END markers (falling back to the existing element on first run),
 * and the matching stylesheet / script tags are ensured.
 *
 * Edit the partial (or its CSS), then run:  node scripts/sync-partials.js
 * (Can be wired as the Cloudflare Pages build command to run on deploy.)
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');

const PARTIALS = [
  {
    tag: 'NAV',
    html: read('partials/nav.html').trim(),
    fallback: /<header id="top-nav">[\s\S]*?<\/header>/,
    cssLink: '<link rel="stylesheet" href="/assets/css/nav.css" />',
    cssTest: /<link[^>]*nav\.css/,
    jsTag: '<script src="/assets/js/nav.js" defer></script>',
    jsTest: /<script[^>]*nav\.js/,
  },
  {
    tag: 'FOOTER',
    html: read('partials/footer.html').trim(),
    fallback: /<footer[\s\S]*?<\/footer>/,
    cssLink: '<link rel="stylesheet" href="/assets/css/footer.css" />',
    cssTest: /<link[^>]*footer\.css/,
    jsTag: null,
    jsTest: null,
  },
];

const pages = fs.readdirSync(ROOT).filter((f) => f.endsWith('.html'));

let changed = 0;
for (const file of pages) {
  const full = path.join(ROOT, file);
  let html = fs.readFileSync(full, 'utf8');
  const before = html;

  for (const p of PARTIALS) {
    const start = `<!-- ${p.tag}:START (generated by scripts/sync-partials.js — edit the partial) -->`;
    const end = `<!-- ${p.tag}:END -->`;
    const block = start + '\n' + p.html + '\n' + end;
    const markerRe = new RegExp(`<!-- ${p.tag}:START[\\s\\S]*?${p.tag}:END -->`);

    if (markerRe.test(html)) {
      html = html.replace(markerRe, block);
    } else if (p.fallback.test(html)) {
      html = html.replace(p.fallback, block);
    } else {
      console.warn(`  ⚠ ${file}: no ${p.tag} markers or fallback element — skipped`);
      continue;
    }

    if (p.cssTest && !p.cssTest.test(html)) {
      html = html.replace('</head>', '  ' + p.cssLink + '\n</head>');
    }
    if (p.jsTest && !p.jsTest.test(html)) {
      html = html.replace('</body>', p.jsTag + '\n</body>');
    }
  }

  if (html !== before) {
    fs.writeFileSync(full, html);
    console.log(`  ✓ ${file}`);
    changed++;
  } else {
    console.log(`  · ${file} (already up to date)`);
  }
}

// Also keep the edge-rendered episode pages (functions/_middleware.js) in
// sync — marker-based only. Its <head>/<body> are template-generated, so the
// nav.css/footer.css link tags there are managed by hand, not by this script.
const MW = path.join(ROOT, 'functions', '_middleware.js');
if (fs.existsSync(MW)) {
  let mw = fs.readFileSync(MW, 'utf8');
  const before = mw;
  for (const p of PARTIALS) {
    const start = `<!-- ${p.tag}:START (generated by scripts/sync-partials.js — edit the partial) -->`;
    const end = `<!-- ${p.tag}:END -->`;
    const block = start + '\n' + p.html + '\n' + end;
    const markerRe = new RegExp(`<!-- ${p.tag}:START[\\s\\S]*?${p.tag}:END -->`);
    if (markerRe.test(mw)) mw = mw.replace(markerRe, block);
  }
  if (mw !== before) {
    fs.writeFileSync(MW, mw);
    console.log('  ✓ functions/_middleware.js');
    changed++;
  } else {
    console.log('  · functions/_middleware.js (already up to date)');
  }
}

console.log(`\nDone — ${changed} file(s) updated.`);
